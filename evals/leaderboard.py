"""Regenerate results/leaderboard.md from every result JSON in a directory."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any


def _size_order(size: str) -> tuple[int, int, str]:
    return (0, int(size), "") if size.isdigit() else (1, 0, size)


def _rate(value: float | None) -> str:
    return "–" if value is None else f"{value:.2f}"


def _cell(group: dict[str, Any] | None) -> str:
    if group is None:
        return "–"
    return " / ".join(_rate(group.get(key)) for key in ("pass_at_1", "pass_hat_k", "duplicate_rate"))


def write_leaderboard(results_dir: Path) -> Path:
    runs = []
    for path in sorted(results_dir.glob("*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if "meta" in data and "summary" in data:
            runs.append((path.stem, data))
    sizes = sorted({size for _, data in runs for size in data["summary"].get("routing", {})}, key=_size_order)
    lines = [
        "# Eval leaderboard",
        "",
        "Each cell: pass@1 / pass^k / duplicate rate (– when no non-error sample). Cost is attributed",
        "cost, Fresh is what the run itself spent; Errors and Incomplete are summed over sizes.",
        "Generated by `evals/leaderboard.py`; do not edit.",
        "",
        "| Run | System | Split | Valid | " + " | ".join(f"n={size}" for size in sizes)
        + " | Errors | Incomplete | Cost | Fresh |",
        "|" + "---|" * (8 + len(sizes)),
    ]
    for stem, data in runs:
        meta, routing = data["meta"], data["summary"].get("routing", {})
        cells = [_cell(routing.get(size)) for size in sizes]
        groups = list(routing.values())
        errors = sum(group.get("error_count", 0) for group in groups)
        incomplete = sum(group.get("incomplete_cases", 0) for group in groups)
        cost = sum(group.get("total_cost_usd", 0.0) for group in groups)
        fresh = sum(group.get("fresh_cost_usd", 0.0) for group in groups)
        valid = "yes" if meta.get("valid") else "**no**"
        if meta.get("budget_exhausted"):
            valid += " (budget hit)"
        lines.append(
            f"| {stem} | {meta.get('system', '?')} | {meta.get('split', '?')} | {valid} | " + " | ".join(cells)
            + f" | {errors} | {incomplete} | ${cost:.2f} | ${fresh:.2f} |"
        )
    out = results_dir / "leaderboard.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
